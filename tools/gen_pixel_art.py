def rows_of(sprite: str) -> list[str]:
    lines = [ln for ln in sprite.strip("\n").split("\n")]
    width = max(len(ln) for ln in lines)
    return [ln.ljust(width, ".") for ln in lines]


def rgba_of(rows: list[str], scale: int = 1) -> tuple[int, int, list[bytes]]:
    h, w = len(rows), len(rows[0])
    out_w, out_h = w * scale, h * scale
    raw_rows: list[bytes] = []
    for y in range(out_h):
        src = rows[y // scale]
        buf = bytearray()
        for x in range(out_w):
            ch = src[x // scale]
            col = PALETTE.get(ch, PALETTE["K"])
            if col is None:
                buf.extend((0, 0, 0, 0))
            else:
                buf.extend(col)
        raw_rows.append(bytes(buf))
    return out_w, out_h, raw_rows


def write_png(path: Path, w: int, h: int, raw_rows: list[bytes]) -> None:
    def chunk(tag: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(tag + data) & 0xFFFFFFFF
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", crc)

    raw = b"".join(b"\x00" + r for r in raw_rows)
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)


def write_image_meta(path: Path, uid: str) -> None:
    meta = {
        "ver": "1.0.27",
        "importer": "image",
        "imported": True,
        "uuid": uid,
        "files": [".json"],
        "subMetas": {},
        "userData": {"type": "sprite-frame", "hasAlpha": True, "fixAlphaTransparencyArtifacts": False},
    }
    path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")


def write_dir_meta(path: Path) -> None:
    path.write_text(
        json.dumps(
            {
                "ver": "1.1.0",
                "importer": "directory",
                "imported": True,
                "uuid": str(uuid.uuid4()),
                "files": [],
                "subMetas": {},
                "userData": {},
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def pal_ts() -> str:
    lines = ["export const PIXEL_PALETTE: Record<string, number | null> = {"]
    for ch, col in PALETTE.items():
        key = "'.'" if ch == "." else f"'{ch}'"
        if col is None:
            lines.append(f"    {key}: null,")
        else:
            r, g, b, a = col
            lines.append(f"    {key}: 0x{r:02x}{g:02x}{b:02x}{a:02x},")
    lines.append("};")
    return "\n".join(lines)


def sprites_ts() -> str:
    parts = ["export const PIXEL_SPRITES: Record<string, string[]> = {"]
    for name, raw in SPRITES.items():
        rows = rows_of(raw)
        parts.append(f"    {name}: [")
        for row in rows:
            parts.append(f"        '{row}',")
        parts.append("    ],")
    parts.append("};")
    return "\n".join(parts)


def compose_icon() -> tuple[int, int, list[bytes]]:
    size = 64
    canvas = [["Z"] * size for _ in range(size)]
    for y in range(size):
        for x in range(size):
            if y > 48:
                canvas[y][x] = "H" if (x + y) % 3 else "A"
    def blit(name: str, ox: int, oy: int) -> None:
        rows = rows_of(SPRITES[name])
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch != "." and 0 <= oy + y < size and 0 <= ox + x < size:
                    canvas[oy + y][ox + x] = ch
    blit("base", 16, 28)
    blit("mg_l2", 6, 18)
    blit("cannon_l1", 40, 16)
    blit("z1", 8, 4)
    blit("z3", 28, 2)
    blit("z2", 46, 6)
    joined = ["".join(r) for r in canvas]
    return rgba_of(joined, scale=16)  # 64*16 = 1024


def compose_share() -> tuple[int, int, list[bytes]]:
    # 80x64 * 8 = 640x512
    w, h = 80, 64
    canvas = [["Z"] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if y > 50:
                canvas[y][x] = "H"
    def blit(name: str, ox: int, oy: int) -> None:
        rows = rows_of(SPRITES[name])
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch != "." and 0 <= oy + y < h and 0 <= ox + x < w:
                    canvas[oy + y][ox + x] = ch
    blit("base", 24, 36)
    blit("mg_l1", 10, 28)
    blit("cannon_l1", 50, 26)
    blit("z1", 6, 12)
    blit("z2", 30, 8)
    blit("z3", 52, 10)
    return rgba_of(["".join(r) for r in canvas], scale=8)


def compose_splash() -> tuple[int, int, list[bytes]]:
    # 45x80 * 16 = 720x1280
    w, h = 45, 80
    canvas = [["Z"] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if y > 68:
                canvas[y][x] = "H" if (x + y) % 2 == 0 else "A"
    def blit(name: str, ox: int, oy: int) -> None:
        rows = rows_of(SPRITES[name])
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch != "." and 0 <= oy + y < h and 0 <= ox + x < w:
                    canvas[oy + y][ox + x] = ch
    blit("base", 6, 48)
    blit("mg_l2", 4, 36)
    blit("cannon_l2", 24, 34)
    blit("z3", 12, 18)
    blit("z1", 2, 22)
    blit("z2", 30, 24)
    return rgba_of(["".join(r) for r in canvas], scale=16)


def main() -> None:
    tex_dir = ROOT / "assets/textures/pixel"
    brand_dir = ROOT / "assets/branding"
    tex_dir.mkdir(parents=True, exist_ok=True)
    brand_dir.mkdir(parents=True, exist_ok=True)
    write_dir_meta(ROOT / "assets/textures.meta")
    write_dir_meta(ROOT / "assets/textures/pixel.meta")
    write_dir_meta(ROOT / "assets/branding.meta")

    for name, raw in SPRITES.items():
        w, h, rows = rgba_of(rows_of(raw), scale=8)
        png = tex_dir / f"{name}.png"
        write_png(png, w, h, rows)
        write_image_meta(tex_dir / f"{name}.png.meta", str(uuid.uuid4()))
        print(f"sprite {name} {w}x{h}")

    for fname, composer in (
        ("icon_1024.png", compose_icon),
        ("share_placeholder.png", compose_share),
        ("splash_placeholder.png", compose_splash),
    ):
        w, h, rows = composer()
        write_png(brand_dir / fname, w, h, rows)
        write_image_meta(brand_dir / f"{fname}.meta", str(uuid.uuid4()))
        print(f"brand {fname} {w}x{h}")

    ts = ROOT / "assets/scripts/pixel/PixelMaps.ts"
    ts.parent.mkdir(parents=True, exist_ok=True)
    ts.write_text(
        "/**\n * PixelMaps.ts — 像素图数据（由 tools/gen_pixel_art.py 生成，可手改后再跑脚本）\n"
        " * 无 Cocos 依赖。\n */\n\n"
        + pal_ts()
        + "\n\n"
        + sprites_ts()
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {ts}")


if __name__ == "__main__":
    main()
